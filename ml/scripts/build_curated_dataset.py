def priority_for(text: str) -> str:
    """Heuristic-based priority used ONLY for templated train items per
    category. Hard, validation and test items have manually labeled priorities."""
    normalized = text.casefold()
    if any(term in normalized for term in HIGH_TERMS):
        return "high"
    if any(term in normalized for term in LOW_TERMS):
        return "low"
    return "medium"


def role_for(category: str, index: int) -> str:
    if category in TEACHER_CATEGORIES and index % 5 == 0:
        return "teacher"
    return "student"


def build_train_items(category: str, category_index: int) -> list[tuple[str, str]]:
    """Returns 54 (text, priority) pairs: 30 templated + 24 hard."""
    topics = CATEGORY_TOPICS[category]
    if len(topics) != 10:
        raise ValueError(f"{category} must have exactly 10 train topics, got {len(topics)}.")
    hard_cases = (
        CATEGORY_HARD_TRAIN_REQUESTS.get(category, [])
        + CATEGORY_EXTRA_HARD_TRAIN_REQUESTS.get(category, [])
        + CATEGORY_PRIORITY_EDGE_CASES.get(category, [])
    )
    if len(hard_cases) != HARD_PER_CATEGORY:
        raise ValueError(
            f"{category} must have exactly {HARD_PER_CATEGORY} hard requests, got {len(hard_cases)}."
        )

    # Deterministic shuffle so all 6 templates and all 10 topics appear in the
    # Selected templated items (avoids losing template #6 or last topic).
    rng = random.Random(42 + category_index)
    combos = [(template, topic) for template in TRAIN_TEMPLATES for topic in topics]
    rng.shuffle(combos)
    templated_target = TRAIN_PER_CATEGORY - len(hard_cases)
    candidates = [
        (template.format(topic=topic), priority_for(template.format(topic=topic)))
        for template, topic in combos
    ]
    buckets = {priority: [] for priority in ("low", "medium", "high")}
    for item in candidates:
        buckets[item[1]].append(item)

    selected: list[tuple[str, str]] = []
    selected_texts: set[str] = set()
    base_quota = templated_target // 3
    remainder = templated_target % 3
    quotas = {
        "low": base_quota + (1 if remainder > 0 else 0),
        "high": base_quota + (1 if remainder > 1 else 0),
        "medium": base_quota,
    }
    for priority in ("low", "high", "medium"):
        for text, item_priority in buckets[priority][: quotas[priority]]:
            selected.append((text, item_priority))
            selected_texts.add(text)

    if len(selected) < templated_target:
        for text, item_priority in candidates:
            if text in selected_texts:
                continue
            selected.append((text, item_priority))
            selected_texts.add(text)
            if len(selected) == templated_target:
                break

    return selected + list(hard_cases)


def build_examples() -> list[dict]:
    examples: list[dict] = []
    for category_index, category in enumerate(CATEGORY_TOPICS):
        train_items = build_train_items(category, category_index)
        validation_items = CATEGORY_VALIDATION_REQUESTS.get(category, [])
        test_items = CATEGORY_TEST_REQUESTS.get(category, [])

        if len(train_items) != TRAIN_PER_CATEGORY:
            raise ValueError(f"{category} train has {len(train_items)} != {TRAIN_PER_CATEGORY}.")
        if len(validation_items) != VALIDATION_PER_CATEGORY:
            raise ValueError(
                f"{category} validation has {len(validation_items)} != {VALIDATION_PER_CATEGORY}."
            )
        if len(test_items) != TEST_PER_CATEGORY:
            raise ValueError(f"{category} test has {len(test_items)} != {TEST_PER_CATEGORY}.")

        for index, (text, priority) in enumerate(train_items):
            examples.append({
                "split": "train",
                "role": role_for(category, index),
                "text": text,
                "category": category,
                "priority": priority,
            })
        for index, (text, priority) in enumerate(validation_items, start=len(train_items)):
            examples.append({
                "split": "validation",
                "role": role_for(category, index),
                "text": text,
                "category": category,
                "priority": priority,
            })
        for index, (text, priority) in enumerate(
            test_items, start=len(train_items) + len(validation_items)
        ):
            examples.append({
                "split": "test",
                "role": role_for(category, index),
                "text": text,
                "category": category,
                "priority": priority,
            })
    return examples


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path("ml/data/curated/tickets_curated.jsonl"))
    args = parser.parse_args()

    examples = build_examples()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as file:
        for example in examples:
            file.write(json.dumps(example, ensure_ascii=False) + "\n")

    print(f"Wrote {len(examples)} examples to {args.output}")


if __name__ == "__main__":
    main()
